"""Размеченный набор для Citation Verifier — тезис, норма, ожидаемый вердикт.

Зачем отдельный набор. `golden.py` меряет поиск: находит ли система нужную
статью по вопросу. Верификатор он не трогает вообще — на экстрактивном ответе
норма и есть ответ, entailment не применяется, и прогон golden set даёт ноль
вызовов `verify()`. То есть компонент, в честь которого назван продукт
(«citations are checked, not asserted»), до сих пор не измерялся ничем: ни
тестом, ни eval.

Критерий разметки. Вердикт определяется **текстом самой нормы**, а не темой:

    SUPPORTS     норма содержит основание для тезиса — прочитав норму, тезис
                 следует из неё
    CONTRADICTS  норма утверждает обратное тезису
    UNRELATED    норма не даёт ни основания, ни опровержения, даже если речь
                 об одном и том же

Треть набора — именно третий случай, и намеренно из соседних пунктов той же
статьи: ст. 431 ч. 1 про буквальное значение слов и ч. 2 про действительную
волю сторон говорят о толковании договора обе, но подтверждают разные тезисы.
Ретривер такие пары возвращает вместе, и верификатор, который их не различает,
не проверяет ничего — он повторяет вывод поиска.

Набор сознательно не про «сложное право». Каждая пара разрешима из процитированного
абзаца без знания практики, иначе она мерила бы не верификатор, а знание Кодекса.
"""

