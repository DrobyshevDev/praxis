def counts_by_verdict() -> dict[Verdict, int]:
    """Сколько пар каждого класса — набор задуман сбалансированным."""
    counts: dict[Verdict, int] = {v: 0 for v in Verdict}
    for case in VERIFIER_SET:
        counts[case.expected] += 1
    return counts
