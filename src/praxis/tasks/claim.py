"""Генератор досудебной претензии из найденных норм.

Превращает ответ Praxis в готовую претензию: правовое обоснование собирается из
**реально процитированных норм** (их текст цитируется дословно), требования и
последствия — фиксированные статутные блоки, а факты дела вынесены в плейсхолдеры
[в скобках] для заполнения пользователем. Модель ничего не сочиняет — это шаблон,
грунтованный по построению, ровно как экстрактивный ответ.

Применимо к гражданско-потребительским вопросам (ГК/ЗоЗПП). Для уголовных,
административных, налоговых вопросов претензия к продавцу не по адресу — возвращаем
`applicable=False` с пояснением.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ..core.models import Answer

# Акты, по которым досудебная претензия к контрагенту осмысленна.
_CIVIL_ACTS = {"zozpp", "gk-rf"}
_QUOTE_CAP = 280  # длинные нормы (напр. ст.18 ЗоЗПП) обрезаем в обосновании

_DISCLAIMER = (
    "Это шаблон, а не юридическая консультация. Проверьте факты, суммы и актуальность "
    "норм, заполните поля в квадратных скобках. При отказе — обращение в суд."
)


@dataclass
class ClaimResult:
    applicable: bool
    text: str = ""
    based_on: list[str] = field(default_factory=list)  # нормы-основания
    note: str = ""  # пояснение, когда претензия неприменима
    disclaimer: str = _DISCLAIMER


def claim_applicable(answer: Answer) -> bool:
    """Претензия имеет смысл, если среди норм есть гражданско-потребительские."""
    return any(c.provision.act.id in _CIVIL_ACTS for c in answer.citations)


def _trim(text: str) -> str:
    text = " ".join(text.split())
    return text if len(text) <= _QUOTE_CAP else text[:_QUOTE_CAP].rstrip() + "…"


def build_claim(answer: Answer) -> ClaimResult:
    """Собрать претензию из ответа (по его цитатам-нормам)."""
    if not answer.citations:
        return ClaimResult(False, note="Не найдено норм — не из чего собрать претензию.")
    if not claim_applicable(answer):
        acts = ", ".join(dict.fromkeys(c.provision.act.short_title for c in answer.citations))
        return ClaimResult(
            False,
            note=(
                f"Для этого вопроса претензия к продавцу неприменима (нормы: {acts}). "
                "Претензия составляется по гражданско-правовым и потребительским спорам."
            ),
        )

    is_consumer = any(c.provision.act.id == "zozpp" for c in answer.citations)
    based_on = list(dict.fromkeys(c.provision.citation for c in answer.citations))

    grounds = [
        f"— согласно {c.provision.citation} ({c.provision.article_title}): "
        f"«{_trim(c.provision.text)}»;"
        for c in answer.citations
    ]

    if is_consumer:
        demand = (
            "На основании изложенного и приведённых норм ТРЕБУЮ (выберите нужное):\n"
            "  • заменить товар на товар надлежащего качества; либо\n"
            "  • вернуть уплаченную за товар сумму [сумма] руб.; либо\n"
            "  • безвозмездно устранить недостатки товара; либо\n"
            "  • соразмерно уменьшить покупную цену.\n\n"
            "Прошу рассмотреть претензию и удовлетворить требование в течение 10 дней "
            "с момента её получения (ст. 22 Закона «О защите прав потребителей»)."
        )
        consequences = (
            "В случае отказа или оставления претензии без ответа я вправе обратиться в суд. "
            "При удовлетворении требований судом с Вас дополнительно подлежат взысканию: "
            "неустойка 1% цены товара за каждый день просрочки (ст. 23), штраф в размере 50% "
            "присуждённой суммы (п. 6 ст. 13), компенсация морального вреда (ст. 15 Закона "
            "«О защите прав потребителей»)."
        )
    else:
        demand = (
            "На основании изложенного и приведённых норм ТРЕБУЮ в срок [срок] дней:\n"
            "  • [сформулируйте требование: исполнить обязательство / вернуть сумму [сумма] руб. "
            "/ возместить убытки].\n\n"
            "Прошу рассмотреть настоящую претензию в разумный срок и удовлетворить требование "
            "в добровольном порядке."
        )
        consequences = (
            "В случае отказа или оставления претензии без ответа оставляю за собой право "
            "обратиться в суд с отнесением на Вас судебных расходов и взысканием процентов "
            "за пользование чужими денежными средствами (ст. 395 ГК РФ)."
        )

    parts = [
        "ПРЕТЕНЗИЯ",
        "",
        "Кому: [наименование продавца/исполнителя]",
        "Адрес: [адрес продавца]",
        "",
        "От: [ФИО потребителя]",
        "Адрес: [ваш адрес], телефон: [ваш телефон]",
        "",
        "[дата] я приобрёл(а) у Вас [наименование товара/услуги] стоимостью [сумма] руб., "
        "что подтверждается [кассовым чеком/договором].",
        "[Опишите проблему: какой недостаток обнаружен и когда.]",
        "",
        "Правовое обоснование:",
        *grounds,
        "",
        demand,
        "",
        consequences,
        "",
        "Приложения: [копии чека, договора и иных документов].",
        "",
        "Дата: [дата]                     Подпись: __________ /[ФИО]/",
    ]
    return ClaimResult(True, text="\n".join(parts), based_on=based_on)
