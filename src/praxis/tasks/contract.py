@dataclass
class ContractCheck:
    label: str
    status: str  # ok | missing | warning
    citation: str
    source_url: str | None
    note: str


@dataclass
class ContractReview:
    ok: bool  # удалось ли проверить (достаточно текста)
    checks: list[ContractCheck] = field(default_factory=list)
    summary: str = ""
    note: str = ""
    disclaimer: str = _DISCLAIMER


def review_contract(text: str) -> ContractReview:
    """Прогнать текст договора по чек-листу."""
    body = (text or "").strip()
    if len(body) < 40:
        return ContractReview(False, note="Вставьте текст договора (не короче 40 символов).")

    low = body.lower()
    checks: list[ContractCheck] = []
    missing = warnings = 0
    for c in _CHECKS:
        hit = any(p in low for p in c.patterns)
        if c.kind == "presence":
            status = "ok" if hit else "missing"
            note = c.ok_note if hit else c.miss_note
            if not hit:
                missing += 1
        else:  # risk
            status = "warning" if hit else "ok"
            note = c.hit_note if hit else c.ok_note
            if hit:
                warnings += 1
        checks.append(ContractCheck(
            c.label, status, c.citation, verify_url(c.act_id, c.article), note,
        ))

    summary = (
        f"Проверено пунктов: {len(checks)}. "
        f"Отсутствуют условия: {missing}. Требуют внимания: {warnings}."
    )
    return ContractReview(True, checks=checks, summary=summary)
