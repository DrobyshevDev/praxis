"""Генератор искового заявления из найденных норм.

Следующий шаг после претензии: если требование не удовлетворено добровольно —
иск в суд. Правовое обоснование, как и в претензии, собирается из реально
процитированных норм (дословно); просительная часть, досудебный порядок,
подсудность и госпошлина — статутные блоки; факты — плейсхолдеры.

Применимость та же, что у претензии (гражданско-потребительские вопросы), поэтому
переиспользуем `claim_applicable`.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from ..core.models import Answer
from .claim import _trim, claim_applicable

_DISCLAIMER = (
    "Это шаблон процессуального документа, а не юридическая консультация. Проверьте "
    "подсудность, суммы и актуальность норм, заполните поля в скобках. Требования к форме "
    "иска — ст. 131, 132 ГПК РФ."
)


@dataclass
class LawsuitResult:
    applicable: bool
    text: str = ""
    based_on: list[str] = field(default_factory=list)
    note: str = ""
    disclaimer: str = _DISCLAIMER


def build_lawsuit(answer: Answer) -> LawsuitResult:
    """Собрать исковое заявление из ответа (по его цитатам-нормам)."""
    if not answer.citations:
        return LawsuitResult(False, note="Не найдено норм — не из чего собрать иск.")
    if not claim_applicable(answer):
        acts = ", ".join(dict.fromkeys(c.provision.act.short_title for c in answer.citations))
        return LawsuitResult(
            False,
            note=(
                f"Для этого вопроса гражданский иск неприменим (нормы: {acts}). "
                "Иск в порядке ГПК составляется по гражданско-правовым и потребительским спорам."
            ),
        )

    is_consumer = any(c.provision.act.id == "zozpp" for c in answer.citations)
    based_on = list(dict.fromkeys(c.provision.citation for c in answer.citations))
    grounds = [
        f"— согласно {c.provision.citation} ({c.provision.article_title}): "
        f"«{_trim(c.provision.text)}»;"
        for c in answer.citations
    ]

    if is_consumer:
        header_extra = [
            "Цена иска: [сумма] руб.",
            "Госпошлина: не уплачивается — иск о защите прав потребителей при цене иска до "
            "1 000 000 руб. (п. 3 ст. 333.36 НК РФ); при превышении — по ст. 333.19 НК РФ.",
        ]
        kind_line = "ИСКОВОЕ ЗАЯВЛЕНИЕ\nо защите прав потребителя"
        jurisdiction = (
            "Иск подан по месту моего жительства (п. 2 ст. 17 Закона «О защите прав "
            "потребителей», ст. 29 ГПК РФ)."
        )
        demands = [
            "1. Взыскать с ответчика уплаченную по договору сумму [сумма] руб. / обязать "
            "заменить товар / устранить недостатки (нужное указать).",
            "2. Взыскать неустойку за просрочку в размере [сумма] руб. (ст. 23 Закона «О "
            "защите прав потребителей»; расчёт прилагается).",
            "3. Взыскать компенсацию морального вреда в размере [сумма] руб. (ст. 15 Закона).",
            "4. Взыскать штраф в размере 50% присуждённой суммы за отказ добровольно "
            "удовлетворить требования (п. 6 ст. 13 Закона).",
        ]
        rukovodstvuyas = (
            "руководствуясь ст. 13, 15, 17, 23 Закона «О защите прав потребителей», "
            "ст. 131, 132 ГПК РФ"
        )
    else:
        header_extra = [
            "Цена иска: [сумма] руб.",
            "Госпошлина: [рассчитайте по ст. 333.19 НК РФ; квитанция прилагается].",
        ]
        kind_line = "ИСКОВОЕ ЗАЯВЛЕНИЕ\nо взыскании [задолженности / убытков]"
        jurisdiction = "Иск подан по месту нахождения ответчика (ст. 28 ГПК РФ)."
        demands = [
            "1. Взыскать с ответчика [сумму долга / убытков] в размере [сумма] руб.",
            "2. Взыскать проценты за пользование чужими денежными средствами (ст. 395 ГК РФ) "
            "в размере [сумма] руб.",
        ]
        rukovodstvuyas = "руководствуясь ст. 131, 132 ГПК РФ"

    parts = [
        "В [наименование суда]",
        "Адрес: [адрес суда]",
        "",
        "Истец: [ФИО], адрес: [ваш адрес], телефон: [телефон]",
        "Ответчик: [наименование продавца/исполнителя], адрес: [адрес ответчика]",
        *header_extra,
        "",
        kind_line,
        "",
        "[дата] между мной и ответчиком заключён договор, во исполнение которого я "
        "приобрёл(а) [наименование товара/услуги] стоимостью [сумма] руб., что "
        "подтверждается [кассовым чеком/договором].",
        "[Опишите нарушение: какой недостаток обнаружен и когда.]",
        "[дата] я направил(а) ответчику претензию, которая оставлена без удовлетворения "
        "(без ответа). Досудебный порядок соблюдён.",
        jurisdiction,
        "",
        "Правовое обоснование:",
        *grounds,
        "",
        f"На основании изложенного, {rukovodstvuyas}, ПРОШУ СУД:",
        *demands,
        "",
        "Приложения:",
        "1. Копии договора, кассового/товарного чека.",
        "2. Копия претензии и подтверждение её направления ответчику.",
        "3. Расчёт цены иска и неустойки.",
        "4. Копия искового заявления для ответчика.",
        "",
        "Дата: [дата]                     Подпись: __________ /[ФИО]/",
    ]
    return LawsuitResult(True, text="\n".join(parts), based_on=based_on)
